func TestGenerateKeepalivedConf_Primary(t *testing.T) {
	got, err := GenerateKeepalivedConf(KeepalivedParams{
		Role:      RolePrimary,
		Interface: "eth0",
		VIP:       "192.168.1.100",
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	want := `! keepalived.conf generated by HydraDNS
! Active-passive VRRP failover of the virtual IP ONLY.
! HydraDNS application state is NOT shared or replicated between nodes.
vrrp_instance VI_HYDRA {
    state MASTER
    interface eth0
    virtual_router_id 51
    priority 200
    advert_int 1
    authentication {
        auth_type PASS
        auth_pass hydradns
    }
    virtual_ipaddress {
        192.168.1.100
    }
}
`
	if got != want {
		t.Fatalf("primary config mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

